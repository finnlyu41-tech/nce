import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
const url=s=>'data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(s)).toString('base64');
const pronunciation=url(await readFile(new URL('../app/pronunciation.ts',import.meta.url),'utf8'));
const source=(await readFile(new URL('../map/speaking-model.ts',import.meta.url),'utf8')).replace("'../app/pronunciation'",JSON.stringify(pronunciation));
const {recordedSpeaking,speakingDue,speakingReviewAt}=await import(url(source));
const now=Date.now(),old=now-86400000;
const original={row:1,source:'synthetic-source',takes:[{id:'take-first',at:old,review:false,assisted:true}],comparison:[],correction:{at:old,issues:[{title:'Synthetic issue',action:'Listen again'}]}};
const recalled=recordedSpeaking(original,'take-second',true,false,now);
assert.equal(recalled.recalledAt,now);
const retried=recordedSpeaking(recalled,'take-second',true,true,now+1000);
assert.strictEqual(retried,recalled,'Retry of the same saved take is idempotent and cannot change its time or assistance');
assert.equal(retried.takes.length,2);assert.equal(retried.takes[0].assisted,false);assert.equal(retried.takes[0].at,now);assert.equal(retried.recalledAt,now);
assert.equal(speakingReviewAt(retried),undefined);
assert(speakingDue(original,now));
assert.equal(recordedSpeaking(original,'take-helped',true,true,now).recalledAt,undefined);
assert.equal(recordedSpeaking(original,'take-early',true,false,old+1).recalledAt,undefined);
const replaced=recordedSpeaking(recalled,'take-first',false,true,now+2000);
assert.equal(new Set(replaced.takes.map(t=>t.id)).size,replaced.takes.length);
console.log('Speaking save retry preserves original take ID/time/help/recall, no duplicates; assisted or early attempts do not complete recall. Synthetic functional times only; no clock or profile changes.');
